"""Generates docs/api/ (markdown) from GDScript `##` doc comments under scripts/.

usage: python3 tools/gen_api_docs.py [--check] [--out docs/api] [--src scripts]

One page per script directory (docs/api/scripts.fp.traffic.md) plus docs/api/index.md. For every
script: class_name, extends, the class doc (the `##` block after the header), then its signals,
enums, constants, documented public properties and public functions (top level, names not
starting with `_`) with full signatures and the `##` block above each. A constant without a `##`
block uses its trailing `#` comment. Output is deterministic; --check exits 1 when docs/api does
not match the sources (CI and the docs workflow run it). Rendered to HTML by GitHub Pages.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.checks import common  # noqa: E402

OUT = "docs/api"
SRC = "scripts"
HEADER = "<!-- Generated by tools/gen_api_docs.py from ## doc comments. Do not edit. -->"
DECL_RE = re.compile(
    r"^(?P<annot>(?:@[\w]+(?:\([^)]*\))?\s+)*)(?P<static>static\s+)?(?P<kind>func|signal|const|enum|var|class)\s+(?P<name>[A-Za-z_]\w*)"
)


def _statement(src_lines: list[str], code_lines: list[str], start: int) -> tuple[str, int]:
    """The raw text of the statement starting at line index start (joined continuation lines)."""
    depth, parts, i = 0, [], start
    while i < len(code_lines):
        code = code_lines[i]
        raw = src_lines[i]
        cut = len(raw)
        for k, ch in enumerate(code):
            if ch in "([{":
                depth += 1
            elif ch in ")]}":
                depth -= 1
        stripped = code.rstrip()
        parts.append(raw[: len(stripped)] if len(stripped) < cut else raw)
        if depth <= 0 and not stripped.endswith("\\"):
            break
        i += 1
    return " ".join(" ".join(p.split()) for p in parts).replace("( ", "(").replace(" )", ")"), i


def _func_signature(stmt_raw: str, stmt_code: str) -> str:
    """`func name(args) -> T` without the trailing colon and any one-line body."""
    depth = 0
    for k, ch in enumerate(stmt_code):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == ":" and depth == 0 and ")" in stmt_code[:k]:
            return stmt_raw[:k].strip()
    return stmt_raw.rstrip(":").strip()


def parse_script(src: str) -> dict:
    lx = common.lex_gd(src)
    code_lines = lx.code_lines
    src_lines = lx.src_lines
    comment_at = {ln: text for ln, text in lx.comments}
    info: dict = {"class_name": "", "extends": "", "doc": [], "items": []}
    pending: list[str] = []
    header_done = False
    i = 0
    while i < len(code_lines):
        code = code_lines[i]
        raw = src_lines[i]
        lineno = i + 1
        stripped = raw.strip()
        if stripped.startswith("##"):
            pending.append(stripped[2:].strip())
            i += 1
            continue
        if not code.strip():
            if not stripped:
                if not header_done and info["doc"] == [] and pending and (info["class_name"] or info["extends"]):
                    info["doc"], pending, header_done = pending, [], True
                pending = [] if header_done else pending
            i += 1
            continue
        if code.startswith(("class_name ", "extends ")) or code.startswith("@"):
            m = re.match(r"^(class_name|extends)\s+(.+?)\s*$", code.split(" extends ")[0] if code.startswith("class_name") else code)
            if code.startswith("class_name"):
                info["class_name"] = code.split()[1]
                if " extends " in code:
                    info["extends"] = code.split(" extends ", 1)[1].strip()
            elif m and m.group(1) == "extends":
                info["extends"] = raw.strip()[len("extends ") :].split("#")[0].strip()
            if not code.startswith("@"):
                i += 1
                continue
        if code[0] in " \t":
            pending = []
            i += 1
            continue
        if not header_done and pending and not info["doc"] and (info["class_name"] or info["extends"]):
            info["doc"], pending = pending, []
        header_done = True
        m = DECL_RE.match(code)
        if not m:
            pending = []
            i += 1
            continue
        stmt_raw, end = _statement(src_lines, code_lines, i)
        stmt_code, _ = _statement(code_lines, code_lines, i)
        kind, name = m.group("kind"), m.group("name")
        doc = pending
        pending = []
        if not doc and kind in ("const", "var") and lineno in comment_at:
            trailing = comment_at[lineno].lstrip("#").strip()
            if trailing:
                doc = [trailing]
        item = {"kind": kind, "name": name, "static": bool(m.group("static")), "doc": doc, "line": lineno}
        if kind == "func":
            item["sig"] = _func_signature(stmt_raw, stmt_code)
        elif kind == "signal":
            item["sig"] = stmt_raw.split("signal", 1)[1].strip()
        elif kind == "const":
            val = stmt_raw.split("=", 1)[1].strip() if "=" in stmt_raw else ""
            val = val[1:].strip() if val.startswith("=") else val
            item["value"] = val if len(val) <= 90 else val[:87] + "..."
        elif kind == "var":
            item["sig"] = re.split(r"\s*(?::?=)\s*|\s+#", stmt_raw.split("var", 1)[1].strip())[0]
            item["export"] = "@export" in (m.group("annot") or "")
        elif kind == "enum":
            item["sig"] = stmt_raw.split("enum", 1)[1].strip()
        info["items"].append(item)
        i = end + 1
    if not info["doc"] and pending and not info["items"]:
        info["doc"] = pending
    return info


def _public(item: dict) -> bool:
    if item["name"].startswith("_"):
        return False
    if item["kind"] == "var":
        return bool(item["doc"]) or item.get("export", False)
    return True


def _doc_text(lines: list[str]) -> str:
    return " ".join(x for x in lines if x).strip()


def render_script(path: str, info: dict) -> list[str]:
    out = [f"## `{path}`", ""]
    head = []
    if info["class_name"]:
        head.append(f"class_name `{info['class_name']}`")
    if info["extends"]:
        head.append(f"extends `{info['extends']}`")
    if head:
        out += [" · ".join(head), ""]
    if info["doc"]:
        out += [_doc_text(info["doc"]), ""]
    items = [it for it in info["items"] if _public(it)]
    sections = (
        ("signal", "Signals"),
        ("enum", "Enums"),
        ("const", "Constants"),
        ("var", "Properties"),
        ("class", "Inner classes"),
        ("func", "Functions"),
    )
    for kind, title in sections:
        group = [it for it in items if it["kind"] == kind]
        if not group:
            continue
        out += [f"### {title}", ""]
        for it in group:
            doc = _doc_text(it["doc"])
            if kind == "const":
                label = f"`{it['name']} = {it['value']}`" if it["value"] else f"`{it['name']}`"
            elif kind == "class":
                label = f"`{it['name']}`"
            elif kind == "func":
                label = f"`{it['sig']}`"
            else:
                label = f"`{it['sig']}`"
            out.append(f"- {label}" + (f": {doc}" if doc else ""))
        out.append("")
    if not items and not info["doc"]:
        out += ["(no public API documented)", ""]
    return out


def page_name(directory: str) -> str:
    return directory.replace("/", ".") + ".md"


def render(root: Path, src: str = SRC) -> dict[str, str]:
    """{page file name: markdown} for docs/api."""
    files = [f for f in common.list_files(root, ("*.gd",)) if f.startswith(src.rstrip("/") + "/")]
    by_dir: dict[str, list[str]] = {}
    for f in files:
        by_dir.setdefault(f.rsplit("/", 1)[0], []).append(f)
    pages: dict[str, str] = {}
    index = [HEADER, "", "# GridFall GDScript API", "",
             "Generated from the `##` doc comments in `scripts/`. Regenerate with "
             "`python3 tools/gen_api_docs.py`; CI fails when this folder is stale.", ""]
    for d in sorted(by_dir):
        infos = {f: parse_script(common.read_text(root, f)) for f in sorted(by_dir[d])}
        body = [HEADER, "", f"# `{d}/`", "", "[Index](index.md)", ""]
        index += [f"## [{d}/]({page_name(d)})", ""]
        for f, info in infos.items():
            body += render_script(f, info)
            first = _doc_text(info["doc"]).split(". ")[0].rstrip(".")
            name = f" (`{info['class_name']}`)" if info["class_name"] else ""
            anchor = re.sub(r"[^a-z0-9 _-]", "", f.lower()).replace(" ", "-")
            index.append(f"- [{f.rsplit('/', 1)[1]}]({page_name(d)}#{anchor}){name}" + (f": {first}" if first else ""))
        index.append("")
        pages[page_name(d)] = "\n".join(body).rstrip() + "\n"
    pages["index.md"] = "\n".join(index).rstrip() + "\n"
    return pages


def stale(root: Path, out: str = OUT, src: str = SRC) -> list[str]:
    """Pages that are missing, different or left over in out."""
    want = render(root, src)
    out_dir = root / out
    have = {p.name for p in out_dir.glob("*.md")} if out_dir.is_dir() else set()
    bad = []
    for name, text in sorted(want.items()):
        p = out_dir / name
        if not p.is_file():
            bad.append(f"{out}/{name} missing")
        elif p.read_text(encoding="utf-8") != text:
            bad.append(f"{out}/{name} out of date")
    bad += [f"{out}/{n} has no source directory" for n in sorted(have - set(want))]
    return bad


def write(root: Path, out: str = OUT, src: str = SRC) -> int:
    pages = render(root, src)
    out_dir = root / out
    out_dir.mkdir(parents=True, exist_ok=True)
    for p in out_dir.glob("*.md"):
        if p.name not in pages:
            p.unlink()
    for name, text in pages.items():
        (out_dir / name).write_text(text, encoding="utf-8")
    return len(pages)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=str(common.REPO))
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    root = Path(a.root)
    if a.check:
        bad = stale(root, a.out, a.src)
        for b in bad:
            print(f"api_docs: {b}")
        print("api_docs: " + ("PASS" if not bad else f"FAIL ({len(bad)} stale; run python3 tools/gen_api_docs.py)"))
        return 1 if bad else 0
    n = write(root, a.out, a.src)
    print(f"api_docs: wrote {n} pages to {a.out}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
