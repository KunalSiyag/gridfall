def export_asset(name):
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, name + ".glb")
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_yup=True,
        export_apply=True,
        export_materials="EXPORT",
        export_cameras=False,
        export_lights=False,
    )
    print("WROTE: " + path)


def main():
    argv = sys.argv
    if "--" in argv:
        wanted = argv[argv.index("--") + 1 :]
    else:
        wanted = ["all"]
    if wanted == ["all"] or "all" in wanted:
        wanted = sorted(BUILDERS.keys())
    for name in wanted:
        if name not in BUILDERS:
            print("UNKNOWN ASSET: " + name)
            continue
        clear_scene()
        BUILDERS[name]()
        export_asset(name)


main()
