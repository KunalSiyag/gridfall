_materials = {}


def mat(name):
    if name in _materials:
        return _materials[name]
    color, metallic, roughness, emission, strength = PALETTE[name]
    m = bpy.data.materials.new(name="gf_" + name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = color
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    if emission is not None:
        bsdf.inputs["Emission Color"].default_value = emission
        bsdf.inputs["Emission Strength"].default_value = strength
    _materials[name] = m
    return m


def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    _materials.clear()


def box(material, center, size, name="part", rot_euler=(0.0, 0.0, 0.0)):
    bpy.ops.mesh.primitive_cube_add(size=2.0, location=center, rotation=rot_euler)
    obj = bpy.context.view_layer.objects.active
    obj.name = name
    obj.dimensions = size
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=True)
    obj.data.materials.append(mat(material))
    for poly in obj.data.polygons:
        poly.use_smooth = False
    return obj


