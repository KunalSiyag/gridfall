"""Error-to-insight pipeline for GridFall.

Reads the error tracker's JSON lines (user://ops/errors.jsonl, written by scripts/ops/error_tracker.gd
when GRIDFALL_ERROR_LOG=1 or the error_tracking flag is on), groups them by fingerprint and writes a
markdown report. With --create-issues it plans one GitHub issue per fingerprint (labels bug and
from-error-tracker, deduplicated by a fingerprint marker in the body); --dry-run is the default and
only prints the gh commands, --no-dry-run runs them.

    python3 tools/ops/errors_to_issues.py [errors.jsonl] [--out report.md] [--create-issues [--no-dry-run]]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Iterable, Sequence

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools.ops.common import default_ops_file, iter_jsonl  # noqa: E402

MARKER = "gridfall-error-fingerprint:"
LABELS = ("bug", "from-error-tracker")

Runner = Callable[[list[str]], subprocess.CompletedProcess]


def group_errors(records: Iterable[dict]) -> list[dict]:
    """One summary per fingerprint, most frequent first:
    {fingerprint, count, first_seen, last_seen, type, message, function, file, line, builds,
    sessions, context, breadcrumbs, backtrace}. count uses the tracker's occurrence numbers, so
    repeats it only counted (past its per-fingerprint cap) are included."""
    groups: dict[str, dict] = {}
    for rec in records:
        fp = str(rec.get("fingerprint") or "")
        if not fp:
            continue
        ts = float(rec.get("ts") or 0.0)
        g = groups.get(fp)
        if g is None:
            g = groups[fp] = {
                "fingerprint": fp, "count": 0, "written": 0, "first_seen": ts, "last_seen": ts,
                "type": rec.get("type", "error"), "message": rec.get("message", ""),
                "function": rec.get("function", ""), "file": rec.get("file", ""), "line": rec.get("line", 0),
                "builds": set(), "sessions": {}, "context": {}, "breadcrumbs": [], "backtrace": "",
            }
        g["written"] += 1
        session = str(rec.get("session") or "")
        g["sessions"][session] = max(g["sessions"].get(session, 0), int(rec.get("occurrence") or 1))
        g["first_seen"] = min(g["first_seen"], ts)
        if ts >= g["last_seen"]:
            g["last_seen"] = ts
            g["context"] = rec.get("context") or {}
            g["breadcrumbs"] = list(rec.get("breadcrumbs") or [])
            if rec.get("backtrace"):
                g["backtrace"] = rec["backtrace"]
        if rec.get("build"):
            g["builds"].add(str(rec["build"]))
    out = []
    for g in groups.values():
        g["count"] = max(g["written"], sum(g["sessions"].values()))
        g["builds"] = sorted(g["builds"])
        g["session_count"] = len(g["sessions"])
        del g["sessions"]
        out.append(g)
    out.sort(key=lambda g: (-g["count"], -g["last_seen"]))
    return out


def _iso(ts: float) -> str:
    if not ts:
        return "-"
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")


def _one_line(text: str, limit: int = 100) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 3] + "..."


def issue_title(g: dict) -> str:
    return f"[error-tracker] {_one_line(g['message'] or g['fingerprint'], 90)}"


def issue_body(g: dict) -> str:
    lines = [
        f"<!-- {MARKER} {g['fingerprint']} -->",
        f"**{g['type']}** `{g['file']}:{g['line']}` in `{g['function']}`",
        "",
        f"- Fingerprint: `{g['fingerprint']}`",
        f"- Occurrences: {g['count']} across {g['session_count']} session(s)",
        f"- First seen: {_iso(g['first_seen'])}; last seen: {_iso(g['last_seen'])}",
        f"- Builds: {', '.join(g['builds']) or '-'}",
        "",
        "Message:",
        "```",
        str(g["message"]),
        "```",
        "Context (latest):",
        "```json",
        json.dumps(g["context"], indent=2, sort_keys=True),
        "```",
    ]
    if g["breadcrumbs"]:
        lines += ["Breadcrumbs (latest, oldest first):", "```", *map(str, g["breadcrumbs"]), "```"]
    if g["backtrace"]:
        lines += ["Backtrace:", "```", str(g["backtrace"]), "```"]
    lines += ["", "_Generated by tools/ops/errors_to_issues.py from a local, scrubbed errors.jsonl._"]
    return "\n".join(lines)


def render_report(groups: list[dict], source: str = "") -> str:
    total = sum(g["count"] for g in groups)
    out = ["# GridFall error report", ""]
    if source:
        out.append(f"Source: `{source}`")
    out += [f"{len(groups)} distinct error(s), {total} occurrence(s).", ""]
    if not groups:
        return "\n".join(out + ["No errors recorded."]) + "\n"
    out += ["| # | Count | Type | Location | Message | First seen | Last seen | Fingerprint |",
            "|---|---|---|---|---|---|---|---|"]
    for i, g in enumerate(groups, 1):
        msg = _one_line(g["message"], 80).replace("|", "\\|")
        out.append(f"| {i} | {g['count']} | {g['type']} | `{g['file']}:{g['line']}` | {msg} | "
                   f"{_iso(g['first_seen'])} | {_iso(g['last_seen'])} | `{g['fingerprint']}` |")
    out.append("")
    for i, g in enumerate(groups, 1):
        out += [f"## {i}. {_one_line(g['message'] or g['fingerprint'], 100)}", "", issue_body(g), ""]
    return "\n".join(out) + "\n"


def find_issue(fingerprint: str, run: Runner) -> int | None:
    """Number of an existing issue (any state) whose body carries the fingerprint marker."""
    proc = run(["gh", "issue", "list", "--state", "all", "--search", f"\"{fingerprint}\" in:body",
                "--json", "number,body", "--limit", "20"])
    if proc.returncode != 0:
        raise RuntimeError(f"gh issue list failed: {proc.stderr.strip()}")
    for item in json.loads(proc.stdout or "[]"):
        if f"{MARKER} {fingerprint}" in str(item.get("body", "")):
            return int(item["number"])
    return None


def plan_issue_commands(groups: list[dict], run: Runner | None, min_count: int = 1) -> list[list[str]]:
    """gh commands that create (or comment on, when one exists) an issue per group. run=None skips
    the dedupe lookup (pure dry run)."""
    cmds: list[list[str]] = []
    for g in groups:
        if g["count"] < min_count:
            continue
        existing = find_issue(g["fingerprint"], run) if run is not None else None
        if existing is None:
            cmd = ["gh", "issue", "create", "--title", issue_title(g), "--body", issue_body(g)]
            for label in LABELS:
                cmd += ["--label", label]
        else:
            cmd = ["gh", "issue", "comment", str(existing), "--body",
                   f"Seen again: {g['count']} occurrence(s), last {_iso(g['last_seen'])}.\n\n" + issue_body(g)]
        cmds.append(cmd)
    return cmds


def _default_runner(cmd: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, check=False)


def main(argv: Sequence[str] | None = None, run: Runner | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("path", nargs="?", help="errors.jsonl (default: this project's user://ops/errors.jsonl)")
    ap.add_argument("--out", help="write the markdown report here instead of stdout")
    ap.add_argument("--create-issues", action="store_true", help="create or update one GitHub issue per fingerprint")
    ap.add_argument("--dry-run", action=argparse.BooleanOptionalAction, default=True,
                    help="print gh commands instead of running them (default; --no-dry-run to run)")
    ap.add_argument("--min-count", type=int, default=1, help="only file issues for errors seen at least this often")
    ap.add_argument("--limit", type=int, default=20, help="at most this many issues per run")
    args = ap.parse_args(list(argv) if argv is not None else None)
    path = Path(args.path) if args.path else default_ops_file("errors.jsonl")
    groups = group_errors(iter_jsonl(path))
    report = render_report(groups, str(path))
    if args.out:
        Path(args.out).write_text(report, encoding="utf-8")
        print(f"wrote {args.out}: {len(groups)} fingerprint(s)")
    else:
        sys.stdout.write(report)
    if not args.create_issues:
        return 0
    runner = run or _default_runner
    cmds = plan_issue_commands(groups[: max(0, args.limit)], None if args.dry_run else runner, args.min_count)
    for cmd in cmds:
        if args.dry_run:
            print("DRY RUN:", " ".join(cmd[:4]), f"({cmd[4][:80]!r} ...)" if len(cmd) > 4 else "")
            continue
        proc = runner(cmd)
        if proc.returncode != 0:
            print(f"gh failed ({proc.returncode}): {proc.stderr.strip()}", file=sys.stderr)
            return 1
        print(proc.stdout.strip())
    return 0


if __name__ == "__main__":
    sys.exit(main())
